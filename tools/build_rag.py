"""Generate docs/rag/rules.md (F7 corpus: one chunk per lexical/grammar/sem.* rule) from docs/language-spec.md.

Usage (project root):  python tools/build_rag.py          # write the file
                       python tools/build_rag.py --check  # exit 1 if the file is stale
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from cea.rules import load_rules  # noqa: E402

TARGET = ROOT / "docs" / "rag" / "rules.md"
HEADER = ("<!-- Generated by tools/build_rag.py from docs/language-spec.md. Do not edit by hand. -->\n"
          "# RAG corpus: language rules\n")


def render() -> str:
    out = [HEADER]
    for name, rule in load_rules().items():
        out.append(f"\n## rule: {name}\nkind: {rule.kind}\n\n~~~text\n{rule.text}\n~~~\n")
    return "".join(out)


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    text = render()
    if "--check" in argv:
        return 0 if TARGET.exists() and TARGET.read_text(encoding="utf-8") == text else 1
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
